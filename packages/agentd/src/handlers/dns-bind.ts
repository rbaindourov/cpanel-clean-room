import { SysrootEngine } from '../sysroot.ts';
import type { AgentServer } from '../index.ts';
import {
  DnsUpsertZoneParamsSchema,
  DnsDeleteZoneParamsSchema,
  type DnsUpsertZoneParams,
  type DnsUpsertZoneResult,
  type DnsDeleteZoneParams,
  type DnsDeleteZoneResult,
  type DnsRecordItem,
} from '@cpanel-clean-room/shared';

export class DnsBindHandler {
  sysroot: SysrootEngine;

  constructor(sysroot: SysrootEngine) {
    this.sysroot = sysroot;
  }

  /**
   * RFC 1035: TXT records with values > 255 octets must be chunked into
   * consecutive quoted strings wrapped in parentheses.
   */
  public chunkTxt(value: string): string {
    const totalBytes = Buffer.byteLength(value, 'utf8');
    if (totalBytes <= 255) {
      const escaped = value.replace(/"/g, '\\"');
      return `"${escaped}"`;
    }
    const chunks: string[] = [];
    let currentChunk = '';
    let currentBytes = 0;

    // Iterate by Unicode code point to avoid splitting multi-byte UTF-8 sequences
    for (const char of value) {
      const charBytes = Buffer.byteLength(char, 'utf8');
      if (currentBytes + charBytes > 255) {
        chunks.push(`"${currentChunk.replace(/"/g, '\\"')}"`);
        currentChunk = char;
        currentBytes = charBytes;
      } else {
        currentChunk += char;
        currentBytes += charBytes;
      }
    }
    if (currentChunk.length > 0) {
      chunks.push(`"${currentChunk.replace(/"/g, '\\"')}"`);
    }
    return `( ${chunks.join(' ')} )`;
  }

  /**
   * Computes next serial using YYYYMMDDNN format.
   */
  public computeNextSerial(currentSerial?: number): number {
    const now = new Date();
    const yyyy = now.getUTCFullYear();
    const mm = String(now.getUTCMonth() + 1).padStart(2, '0');
    const dd = String(now.getUTCDate()).padStart(2, '0');
    const datePrefix = parseInt(`${yyyy}${mm}${dd}`, 10);
    const todayBase = datePrefix * 100 + 1;

    if (!currentSerial) {
      return todayBase;
    }

    if (currentSerial >= todayBase) {
      return currentSerial + 1;
    }
    return todayBase;
  }

  public async upsertZone(params: DnsUpsertZoneParams): Promise<DnsUpsertZoneResult> {
    const {
      domain,
      primaryNs = 'ns1.cleanpanel.local.',
      adminEmail = 'hostmaster.cleanpanel.local.',
      ttl = 300,
      records = [],
      syncCloudflare = false,
    } = params;

    const zoneFileRel = `/etc/bind/zones/${domain}.db`;
    let oldSerial: number | undefined;

    if (this.sysroot.exists(zoneFileRel)) {
      const oldContent = this.sysroot.readFile(zoneFileRel);
      const match = oldContent.match(/(\d{10})\s*;\s*serial/i);
      if (match && match[1]) {
        oldSerial = parseInt(match[1], 10);
      }
    }

    const serial = this.computeNextSerial(oldSerial);

    // Format RFC 1035 zone file
    let zoneContent = `; BIND9 zone file for ${domain}
; Auto-generated by cPanel clean-room panel-agentd
$TTL ${ttl}
@ IN SOA ${primaryNs} ${adminEmail} (
    ${serial} ; serial
    10800      ; refresh (3 hours)
    3600       ; retry (1 hour)
    604800     ; expire (1 week)
    300        ; minimum (5 minutes)
)

; Nameservers
@ IN NS ${primaryNs}
`;

    // Add records
    for (const rec of records) {
      const name = rec.name.endsWith('.') || rec.name === '@' ? rec.name : `${rec.name}`;
      const recTtl = rec.ttl ? `${rec.ttl} ` : '';

      if (rec.type === 'TXT') {
        const chunkedVal = this.chunkTxt(rec.value);
        zoneContent += `${name} ${recTtl}IN TXT ${chunkedVal}\n`;
      } else if (rec.type === 'MX') {
        const priority = rec.priority ?? 10;
        zoneContent += `${name} ${recTtl}IN MX ${priority} ${rec.value}\n`;
      } else if (rec.type === 'SRV') {
        const priority = rec.priority !== undefined ? rec.priority : 0;
        zoneContent += `${name} ${recTtl}IN SRV ${priority} ${rec.value}\n`;
      } else {
        zoneContent += `${name} ${recTtl}IN ${rec.type} ${rec.value}\n`;
      }
    }

    this.sysroot.atomicWriteFile(zoneFileRel, zoneContent, { mode: 0o644 });

    // Update /etc/bind/named.conf.local
    const namedConfPath = '/etc/bind/named.conf.local';
    let namedConf = '';
    if (this.sysroot.exists(namedConfPath)) {
      namedConf = this.sysroot.readFile(namedConfPath);
    }
    const zoneBlock = `zone "${domain}" { type master; file "${this.sysroot.resolve(zoneFileRel)}"; };`;
    if (!namedConf.includes(`zone "${domain}"`)) {
      namedConf += `\n${zoneBlock}\n`;
      this.sysroot.atomicWriteFile(namedConfPath, namedConf, { mode: 0o644 });
    }

    // Validate zone syntax
    const checkRes = await this.sysroot.execCommand('named-checkzone', [
      domain,
      this.sysroot.resolve(zoneFileRel),
    ]);
    if (checkRes.code !== 0) {
      const err: any = new Error(`Zone syntax check failed: ${checkRes.stderr}`);
      err.code = 'ZONE_INVALID';
      throw err;
    }

    // Reload BIND9 zone
    await this.sysroot.execCommand('rndc', ['reload', domain]);

    if (syncCloudflare) {
      // Mock / Cloudflare sync audit
      await this.sysroot.execCommand('curl', [
        '-s',
        'https://api.cloudflare.com/client/v4/zones',
      ]);
    }

    return {
      zoneFile: zoneFileRel,
      serial,
      reloaded: true,
    };
  }

  public async deleteZone(params: DnsDeleteZoneParams): Promise<DnsDeleteZoneResult> {
    const { domain } = params;
    const zoneFileRel = `/etc/bind/zones/${domain}.db`;
    this.sysroot.removeFile(zoneFileRel);

    const namedConfPath = '/etc/bind/named.conf.local';
    if (this.sysroot.exists(namedConfPath)) {
      let namedConf = this.sysroot.readFile(namedConfPath);
      const escapedDomain = domain.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const regex = new RegExp(`zone\\s+"${escapedDomain}"\\s*\\{[^\\}]*\\};\\s*\\n?`, 'g');
      namedConf = namedConf.replace(regex, '');
      this.sysroot.atomicWriteFile(namedConfPath, namedConf, { mode: 0o644 });
    }

    await this.sysroot.execCommand('rndc', ['reload']);

    return {
      deleted: true,
      reloaded: true,
    };
  }

  private stripZoneComment(line: string): string {
    let inQuote = false;
    let escape = false;
    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (escape) {
        escape = false;
        continue;
      }
      if (ch === '\\') {
        escape = true;
        continue;
      }
      if (ch === '"') {
        inQuote = !inQuote;
        continue;
      }
      if (!inQuote && (ch === ';' || ch === '#')) {
        return line.slice(0, i).trimEnd();
      }
    }
    return line;
  }

  public parseZone(zoneContent: string): { domain: string; serial: number; records: DnsRecordItem[] } {
    const lines = zoneContent.split(/\r?\n/);
    const records: DnsRecordItem[] = [];
    let domain = '';
    let serial = 0;

    const serialMatch = zoneContent.match(/(\d{10})\s*;\s*serial/i);
    if (serialMatch && serialMatch[1]) {
      serial = parseInt(serialMatch[1], 10);
    }

    for (const rawLine of lines) {
      const lineWithoutComment = this.stripZoneComment(rawLine);
      const trimmed = lineWithoutComment.trim();
      if (!trimmed || trimmed.startsWith('$') || trimmed.includes('SOA')) {
        continue;
      }

      const match = trimmed.match(/^(\S+)\s+(?:(\d+)\s+)?IN\s+([A-Z]+)\s+(.+)$/);
      if (match && match[1] && match[3] && match[4]) {
        const name = match[1];
        const type = match[3] as any;
        const rawVal = match[4].trim();

        if (type === 'MX') {
          const mxParts = rawVal.split(/\s+/);
          records.push({
            name,
            type,
            priority: parseInt(mxParts[0] || '10', 10),
            value: mxParts[1] || '',
          });
        } else if (type === 'SRV') {
          const srvParts = rawVal.split(/\s+/);
          records.push({
            name,
            type,
            priority: parseInt(srvParts[0] || '0', 10),
            value: srvParts.slice(1).join(' ') || '',
          });
        } else if (type === 'TXT') {
          let txtVal = rawVal;
          if (txtVal.startsWith('(') && txtVal.endsWith(')')) {
            txtVal = txtVal.slice(1, -1).trim();
          }
          const quoteRegex = /"((?:[^"\\]|\\.)*)"/g;
          const chunks: string[] = [];
          let matchChunk: RegExpExecArray | null;
          while ((matchChunk = quoteRegex.exec(txtVal)) !== null) {
            chunks.push(matchChunk[1].replace(/\\"/g, '"'));
          }
          const finalVal = chunks.length > 0 ? chunks.join('') : txtVal.replace(/^"|"$/g, '');
          records.push({
            name,
            type,
            value: finalVal,
          });
        } else {
          let cleanVal = rawVal;
          if (cleanVal.startsWith('"') && cleanVal.endsWith('"')) {
            cleanVal = cleanVal.slice(1, -1);
          }
          records.push({
            name,
            type,
            value: cleanVal,
          });
        }
      }
    }

    return { domain, serial, records };
  }
}

export function registerDnsBindHandlers(server: AgentServer): void {
  const handler = new DnsBindHandler(server.getSysroot());

  server.registerHandler('dns.upsertZone', (p) => handler.upsertZone(p), DnsUpsertZoneParamsSchema);
  server.registerHandler('dns.deleteZone', (p) => handler.deleteZone(p), DnsDeleteZoneParamsSchema);
}
